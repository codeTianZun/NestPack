def find_processes(exe_name: str) -> list[int]:
    """用 Windows tasklist 按进程名查找 PID。"""
    result = subprocess.run(
        ["tasklist", "/FI", f"IMAGENAME eq {exe_name}", "/FO", "CSV", "/NH"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    pids: list[int] = []
    for line in result.stdout.splitlines():
        parts = [part.strip('"') for part in line.split('","')]
        if len(parts) >= 2 and parts[0].casefold() == exe_name.casefold():
            try:
                pids.append(int(parts[1]))
            except ValueError:
                pass
    return pids


def kill_processes(pids: list[int]) -> None:
    """用 Windows taskkill 强制结束指定进程。"""
    for pid in pids:
        subprocess.run(["taskkill", "/PID", str(pid), "/F"], check=False)


def ensure_unlocked(no_kill: bool, assume_yes: bool) -> None:
    """确保 dist 中的 exe 没有被正在运行的实例占用。"""
    for exe_name, _name, _entry, _mode in TARGETS:
        pids = find_processes(exe_name)
        if not pids:
            continue
        print(f"{exe_name} is running (PID {', '.join(map(str, pids))}), "
              f"it locks dist\\{exe_name}.")
        if no_kill:
            sys.exit("Aborted: running executable blocks the build. "
                     "Close it or rerun without --no-kill.")
        if assume_yes:
            answer = "Y"
        else:
            answer = input(
                "Terminate it and continue? [Y/N, default Y]: "
            ).strip().upper() or "Y"
        if answer != "Y":
            sys.exit("Aborted, running executables were left untouched.")
        kill_processes(pids)


def generate_icon() -> Path:
    """从应用图像生成多尺寸 ICO 图标（16/24/32/48/64/128/256）。

    输出 ICO 内嵌 32bpp BMP 条目，兼容 Windows 资源管理器与任务栏。
    """
    from PySide6.QtCore import Qt
    from PySide6.QtGui import QGuiApplication, QImage, QPixmap

    from gui.appearance.logo import APP_ICON_PATH

    QGuiApplication.instance() or QGuiApplication([])

    sizes = (16, 24, 32, 48, 64, 128, 256)
    base = QPixmap(str(APP_ICON_PATH)).scaled(
        256, 256,
        Qt.AspectRatioMode.KeepAspectRatio,
        Qt.TransformationMode.SmoothTransformation,
    )

    entries: list[tuple[bytes, int]] = []  # (ICONDIRENTRY, offset)
    payload = bytearray()
    header_size = 6 + 16 * len(sizes)
    for size in sizes:
        pixmap = (
            base if size == 256 else base.scaled(
                size, size,
                Qt.AspectRatioMode.IgnoreAspectRatio,
                Qt.TransformationMode.SmoothTransformation,
            )
        )
        image = pixmap.toImage().convertToFormat(QImage.Format.Format_ARGB32)
        width, height = image.width(), image.height()
        raw = bytes(image.constBits())
        # BMP 行序自下而上；ARGB32 小端内存布局即 BGRA。
        row_stride = width * 4
        xor = bytearray()
        for y in range(height - 1, -1, -1):
            start = y * row_stride
            xor += raw[start:start + row_stride]
        and_row = ((width + 31) // 32) * 4
        bitmap = (
            struct.pack(
                "<IiiHHIIiiII",
                40, width, height * 2, 1, 32, 0, 0, 0, 0, 0, 0,
            )
            + xor
            + bytes(and_row * height)  # 32bpp 全透明 AND 掩码
        )
        entries.append((
            struct.pack(
                "<BBBBHHII",
                0 if size >= 256 else size,
                0 if size >= 256 else size,
                0, 0, 1, 32, len(bitmap), len(payload) + header_size,
            ),
            len(payload),
        ))
        payload += bitmap

    header = struct.pack("<HHH", 0, 1, len(sizes)) + b"".join(
        entry for entry, _offset in entries
    )
    ICON_PATH.parent.mkdir(parents=True, exist_ok=True)
    ICON_PATH.write_bytes(header + payload)
    return ICON_PATH


def collect_licenses() -> None:
    """收集项目与当前平台构建依赖的许可原文。"""
    destination = ROOT / "dist"
    destination.mkdir(exist_ok=True)
    for name in LEGAL_DOCUMENTS:
        shutil.copyfile(ROOT / name, destination / name)
    licenses = destination / "licenses"
    if licenses.exists():
        shutil.rmtree(licenses)
    if sys.platform == "win32":
        shutil.copytree(ROOT / "licenses", licenses)
        names = [
            "PySide6", "PySide6-Essentials", "PySide6-Addons", "shiboken6",
            "PySide6-Fluent-Widgets", "PySideSix-Frameless-Window", "darkdetect",
            "pywin32", "pyinstaller",
        ]
        if sys.version_info < (3, 11):
            names.append("tomli")
    else:
        licenses.mkdir()
        shutil.copyfile(ROOT / "licenses" / "Python-3.12.txt", licenses / "Python-3.12.txt")
        names = ["pyinstaller"]
    for name in names:
        distribution = metadata.distribution(name)
        for relative in distribution.files or ():
            if not any(
                part.lower().startswith(("license", "copying", "notice"))
                for part in relative.parts
            ):
                continue
            source = Path(distribution.locate_file(relative))
            if source.is_file():
                target = licenses / f"{name}-{distribution.version}" / Path(*(
                    part for part in relative.parts if part not in ("..", ".")
                ))
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(source, target)
    python_license = Path(sys.base_prefix) / "LICENSE.txt"
    if python_license.is_file():
        shutil.copyfile(python_license, licenses / "Python.txt")


def write_spec(name: str, entry: str, mode: str) -> Path:
    """生成 build\\<name>.spec，GUI 目标按过滤规则裁剪 Qt 文件。"""
    spec_path = ROOT / "build" / f"{name}.spec"
    spec_path.parent.mkdir(parents=True, exist_ok=True)
    entry_rel = os.path.relpath((ROOT / entry).resolve(), spec_path.parent).replace("\\", "/")
    icon_rel = os.path.relpath(ICON_PATH, spec_path.parent).replace("\\", "/")
    data = [(str(ROOT / "dist" / document), ".") for document in LEGAL_DOCUMENTS]
    data.append((str(ROOT / "dist" / "licenses"), "licenses"))
    if mode == "--windowed":
        data.extend(
            (str(path), "gui/appearance/assets")
            for path in sorted((ROOT / "gui" / "appearance" / "assets").glob("*.png"))
        )
    content = (
        SPEC_TEMPLATE
        .replace("@ENTRY@", entry_rel)
        .replace("@ROOT@", repr(str(ROOT)))
        .replace("@DATA@", repr(data))
        .replace("@NAME@", name)
        .replace("@ICON@", icon_rel)
        .replace("@CONSOLE@", str(mode != "--windowed"))
        .replace("@SLIM@", str(mode == "--windowed"))
    )
    spec_path.write_text(content, encoding="utf-8")
    return spec_path


def run_pyinstaller(name: str, entry: str, mode: str) -> None:
    """以项目内缓存目录运行一次 PyInstaller 构建。"""
    env = os.environ.copy()
    env["PYINSTALLER_CONFIG_DIR"] = str(CACHE_DIR)
    spec_path = write_spec(name, entry, mode)
    command = [
        sys.executable,
        "-m",
        "PyInstaller",
        "--noconfirm",
        str(spec_path),
    ]
    result = subprocess.run(command, cwd=ROOT, env=env)
    if result.returncode != 0:
        sys.exit(f"Failed building {name} (return code {result.returncode}).")


def build_linux_cli() -> None:
    """用 PyInstaller 构建自带 Python 运行时的 Linux CLI。"""
    env = os.environ.copy()
    env["PYINSTALLER_CONFIG_DIR"] = str(CACHE_DIR)
    command = [
        sys.executable, "-m", "PyInstaller", "--noconfirm", "--onefile", "--console",
        "--name", "nestpack-linux-cli", "--distpath", str(ROOT / "dist"),
        "--workpath", str(ROOT / "build" / "linux"),
        "--specpath", str(ROOT / "build"), "--paths", str(ROOT),
    ]
    for document in LEGAL_DOCUMENTS:
        command.extend(("--add-data", f"{ROOT / 'dist' / document}:."))
    command.extend(("--add-data", f"{ROOT / 'dist' / 'licenses'}:licenses"))
    command.append(str(ROOT / "cli" / "__main__.py"))
    result = subprocess.run(command, cwd=ROOT, env=env)
    if result.returncode != 0:
        sys.exit(f"Failed building nestpack-linux-cli (return code {result.returncode}).")


def main() -> int:
    parser = argparse.ArgumentParser(description="构建 Windows GUI/CLI 或 Linux CLI 单文件程序。")
    parser.add_argument(
        "--yes", action="store_true",
        help="terminate running executables without asking",
    )
    parser.add_argument(
        "--no-kill", action="store_true",
        help="fail instead of terminating running executables",
    )
    args = parser.parse_args()

    if sys.platform not in ("win32", "linux"):
        parser.error("NestPack 仅支持 Windows 与 Linux。")
    if sys.platform == "win32" and not (ROOT / ".venv" / "Scripts" / "python.exe").exists():
        print("WARNING: .venv not found; using current interpreter. "
              "Consider creating a virtual environment first.")
    try:
        import PyInstaller  # noqa: F401
    except ImportError:
        print("PyInstaller is not installed; installing ...")
        subprocess.run(
            [sys.executable, "-m", "pip", "install", "-q", "pyinstaller"],
            check=True,
        )

    if sys.platform == "win32":
        ensure_unlocked(args.no_kill, args.yes)
    collect_licenses()

    if sys.platform == "linux":
        build_linux_cli()
        print(f"已生成 {ROOT / 'dist' / 'nestpack-linux-cli'}")
        return 0

    icon_path = generate_icon()
    print(f"Generated icon: {icon_path}")

    total = len(TARGETS)
    for index, (exe_name, name, entry, mode) in enumerate(TARGETS, start=1):
        print(f"\n[{index}/{total}] Building {exe_name} ...")
        run_pyinstaller(name, entry, mode)

    print("\nBuild finished:")
    print(f"  {ROOT / 'dist' / TARGETS[0][0]}      GUI")
    print(f"  {ROOT / 'dist' / TARGETS[1][0]}  CLI")
    print("Default config is created next to each exe.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
