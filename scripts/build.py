import struct
import subprocess
import sys
from importlib import metadata
from pathlib import Path

# 脚本位于 scripts/ 下，项目根是其上一级。
ROOT = Path(__file__).resolve().parent.parent
# 直接 python scripts\build.py 运行时 sys.path 里没有项目根，补上以便导入 gui 包。
sys.path.insert(0, str(ROOT))

